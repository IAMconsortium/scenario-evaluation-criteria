"""mkdocs hook that builds the "Summary" nav subtree from the criteria data.

Criteria are added/removed independently of the docs config, and there are
dozens of them, so the per-type/per-criterion nav entries are generated here
rather than hand-maintained in mkdocs.yml. Only the cheap
``load_criteria_hierarchy`` (no thresholds/region-mapping I/O) is used, so
this runs quickly on every build and on every `mkdocs serve` reload. The
pages it points at are generated by ``gen_summary_pages.py`` from the same
data (an mkdocs-gen-files script), so the two always stay in sync.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from summary_pages import (  # noqa: E402
    criterion_page_slug,
    criterion_type_dir,
    load_criteria_hierarchy,
)


def on_config(config, **kwargs):
    criteria_types, criteria_by_type = load_criteria_hierarchy()

    summary_nav = ["summary/index.md"]
    for crit_type, criteria in criteria_by_type.items():
        if not criteria:
            continue
        type_dir = criterion_type_dir(crit_type)
        type_nav = [f"summary/{type_dir}/index.md"]
        for criterion in criteria:
            display_name = criterion.split("|", 1)[1]
            slug = criterion_page_slug(criterion)
            type_nav.append({display_name: f"summary/{type_dir}/{slug}.md"})
        summary_nav.append({crit_type: type_nav})

    for item in config.nav:
        if isinstance(item, dict) and "Summary" in item:
            item["Summary"] = summary_nav
            break
    else:
        raise Exception("'Summary' entry not found in nav configuration.")

    return config
